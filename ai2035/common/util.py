"""Shared helpers for the ai2035 projects: seeding, result logging, CJK plotting.

Every experiment calls ``save_results`` so that the numbers quoted in a report
can be traced to a JSON file regenerated by ``python experiment.py``.
"""
from __future__ import annotations

import json
import os
import platform
import time
from pathlib import Path

import numpy as np

SEED = 20351


def rng(offset: int = 0) -> np.random.Generator:
    return np.random.default_rng(SEED + offset)


def results_dir(script_file: str) -> Path:
    d = Path(script_file).resolve().parent / "results"
    d.mkdir(exist_ok=True)
    return d


def _jsonable(o):
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    raise TypeError(type(o))


def save_results(script_file: str, payload: dict) -> Path:
    payload = dict(payload)
    payload["_meta"] = {
        "seed": SEED,
        "python": platform.python_version(),
        "numpy": np.__version__,
        "generated": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    p = results_dir(script_file) / "results.json"
    p.write_text(json.dumps(payload, ensure_ascii=False, indent=2, default=_jsonable))
    return p


def mean_ci(x, z: float = 1.96):
    """Mean and normal-approx 95% CI half-width over repeated seeds."""
    x = np.asarray(x, dtype=float)
    if x.size < 2:
        return float(x.mean()), float("nan")
    return float(x.mean()), float(z * x.std(ddof=1) / np.sqrt(x.size))


def plt():
    """matplotlib.pyplot configured for headless use and Chinese labels."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as _plt
    from matplotlib import font_manager

    for path in ("/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc",):
        if os.path.exists(path):
            font_manager.fontManager.addfont(path)
            matplotlib.rcParams["font.sans-serif"] = ["WenQuanYi Zen Hei", "DejaVu Sans"]
    matplotlib.rcParams["axes.unicode_minus"] = False
    matplotlib.rcParams["figure.dpi"] = 110
    return _plt
