"""Run every simulation, write figures and a machine-readable results file.

Usage:  python -m cosmos.run_all            # all ten
        python -m cosmos.run_all 2 8        # only problems 2 and 8
"""
from __future__ import annotations

import importlib
import json
import sys
import time

from .common import OUT

PROBLEMS = {
    1: ("p01_dark_matter", "What is dark matter?"),
    2: ("p02_dark_energy", "Is dark energy constant?"),
    3: ("p03_hubble_tension", "The Hubble tension"),
    4: ("p04_inflation", "What drove inflation?"),
    5: ("p05_baryogenesis", "Why matter and not antimatter?"),
    6: ("p06_black_hole_information", "Black-hole information"),
    7: ("p07_early_black_holes", "Early giant black holes"),
    8: ("p08_structure_and_dipole", "Structure growth and the cosmic dipole"),
    9: ("p09_lithium", "The lithium problem"),
    10: ("p10_neutrino_mass", "Neutrino masses"),
}


def _jsonable(o):
    if hasattr(o, "item"):
        return o.item()
    if hasattr(o, "tolist"):
        return o.tolist()
    raise TypeError(type(o))


def main(argv=None) -> dict:
    which = [int(a) for a in (sys.argv[1:] if argv is None else argv)] or list(PROBLEMS)
    path = OUT / "results.json"
    results = json.loads(path.read_text()) if path.exists() and len(which) < len(PROBLEMS) else {}
    for n in which:
        mod, title = PROBLEMS[n]
        t = time.time()
        res = importlib.import_module(f"cosmos.{mod}").run()
        results[str(n)] = {"problem": title, **res}
        print(f"[{n:2d}] {title:42s} {time.time() - t:5.1f}s  -> {res['figure']}")
    OUT.mkdir(exist_ok=True)
    path.write_text(json.dumps(results, indent=2, default=_jsonable) + "\n")
    lines = ["# Simulation results", "",
             "Generated by `python -m cosmos.run_all`. Full numbers are in `results.json`.", ""]
    for n in sorted(results, key=int):
        r = results[n]
        lines += [f"## {n}. {r['problem']}", "", f"![{r['problem']}]({r['figure'].split('/')[-1]})", "",
                  r["reading"], "", "Limits of this simulation:", ""]
        lines += [f"- {c}" for c in r["caveats"]] + [""]
    (OUT / "REPORT.md").write_text("\n".join(lines))
    return results


if __name__ == "__main__":
    main()
