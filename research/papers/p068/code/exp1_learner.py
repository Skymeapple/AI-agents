"""Experiment 1: microfoundation of H(N) with real learners in a drifting world.

A d-dimensional linear 'world' theta_t drifts as a stationary AR(1).  Each period
creators publish N fresh human works; each work is one noisy observation
(x, y = theta_t.x + e), e ~ N(0, s2).  We measure the steady-state AI quality
q = 1 - E||theta_hat - theta||^2 / E||theta||^2 for
  (a) an exact Kalman tracker (optimal learner),
  (b) a sliding-window OLS learner (no knowledge of the drift; best window chosen),
  (c) the Kalman tracker whose training pool is contaminated by synthetic works
      generated by its own previous model and treated as human data.
Outputs: results/exp1_learner.json, results/fig1_learner.png
"""
import json, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
from commons import H_kalman

OUT = os.path.join(os.path.dirname(__file__), "..", "results")
os.makedirs(OUT, exist_ok=True)
D, PHI, S2 = 10, 0.95, 1000.0
T, BURN = 500, 100


def run_kalman(N, seed, synth_ratio=0.0):
    rng = np.random.default_rng(seed)
    theta = rng.standard_normal(D)
    th = np.zeros(D); P = np.eye(D)
    errs = []
    a = np.sqrt(1 - PHI**2)
    for t in range(T):
        theta = PHI * theta + a * rng.standard_normal(D)
        Pm = PHI**2 * P + (1 - PHI**2) * np.eye(D)
        thm = PHI * th
        X = rng.standard_normal((N, D)); y = X @ theta + np.sqrt(S2) * rng.standard_normal(N)
        m = int(round(synth_ratio * N))
        if m > 0:  # synthetic works produced by the previous model, mislabeled as human
            Xs = rng.standard_normal((m, D)); ys = Xs @ th + np.sqrt(S2) * rng.standard_normal(m)
            X = np.vstack([X, Xs]); y = np.concatenate([y, ys])
        Pinv = np.linalg.inv(Pm) + X.T @ X / S2
        P = np.linalg.inv(Pinv)
        th = P @ (np.linalg.solve(Pm, thm) + X.T @ y / S2)
        if t >= BURN:
            errs.append(np.sum((th - theta) ** 2) / D)
    return 1 - np.mean(errs)


def run_window(N, W, seed):
    rng = np.random.default_rng(seed)
    theta = rng.standard_normal(D)
    a = np.sqrt(1 - PHI**2)
    bufX, bufy, errs = [], [], []
    for t in range(T):
        theta = PHI * theta + a * rng.standard_normal(D)
        X = rng.standard_normal((N, D)); y = X @ theta + np.sqrt(S2) * rng.standard_normal(N)
        bufX.append(X); bufy.append(y)
        bufX, bufy = bufX[-W:], bufy[-W:]
        XX = np.vstack(bufX); yy = np.concatenate(bufy)
        th = np.linalg.solve(XX.T @ XX + 1.0 * S2 * np.eye(D), XX.T @ yy)  # ridge, prior var 1
        if t >= BURN:
            errs.append(np.sum((th - theta) ** 2) / D)
    return 1 - np.mean(errs)


def main():
    Ns = [5, 10, 25, 50, 100, 200, 400, 800]
    seeds = range(10)
    res = {"params": dict(D=D, phi=PHI, s2=S2, T=T, burn=BURN, seeds=len(seeds)),
           "N": Ns, "kalman": [], "kalman_sd": [], "analytic": [], "window": [], "window_W": []}
    for N in Ns:
        q = [run_kalman(N, s) for s in seeds]
        res["kalman"].append(float(np.mean(q))); res["kalman_sd"].append(float(np.std(q)))
        res["analytic"].append(float(H_kalman(N, PHI, S2)))
        best = (-1, None)
        for W in [1, 2, 4, 8, 16, 32, 64]:
            qw = np.mean([run_window(N, W, s) for s in range(3)])
            if qw > best[0]:
                best = (qw, W)
        res["window"].append(float(best[0])); res["window_W"].append(best[1])
        print(f"N={N:4d} kalman={res['kalman'][-1]:.3f}±{res['kalman_sd'][-1]:.3f} "
              f"analytic={res['analytic'][-1]:.3f} window={best[0]:.3f} (W={best[1]})", flush=True)
    # synthetic contamination
    ratios = [0.0, 0.5, 1.0, 2.0, 4.0]
    res["synth_ratios"] = ratios; res["synth"] = {}
    for N in [25, 100, 400]:
        res["synth"][str(N)] = [float(np.mean([run_kalman(N, s, r) for s in range(4)])) for r in ratios]
        print("synthetic N=", N, res["synth"][str(N)], flush=True)
    # max abs gap analytic vs simulated
    res["max_abs_gap_analytic_vs_sim"] = float(np.max(np.abs(np.array(res["kalman"]) - np.array(res["analytic"]))))
    json.dump(res, open(os.path.join(OUT, "exp1_learner.json"), "w"), indent=1)

    import matplotlib; matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(1, 2, figsize=(10, 3.8))
    ax[0].errorbar(Ns, res["kalman"], yerr=res["kalman_sd"], fmt="o", label="Kalman learner (simulated)")
    Ng = np.geomspace(3, 1000, 200)
    ax[0].plot(Ng, H_kalman(Ng, PHI, S2), "-", label="analytic H(N)")
    ax[0].plot(Ns, res["window"], "s--", label="sliding-window ridge (best W)")
    ax[0].set_xscale("log"); ax[0].set_xlabel("fresh human works per period N"); ax[0].set_ylabel("AI quality q")
    ax[0].legend(fontsize=8); ax[0].set_title("(a) quality depends on the flow of fresh works")
    for N in [25, 100, 400]:
        ax[1].plot(ratios, res["synth"][str(N)], "o-", label=f"N={N}")
    ax[1].set_xlabel("synthetic works per human work (treated as human)"); ax[1].set_ylabel("AI quality q")
    ax[1].legend(fontsize=8); ax[1].set_title("(b) synthetic substitutes do not replace fresh works")
    fig.tight_layout(); fig.savefig(os.path.join(OUT, "fig1_learner.png"), dpi=150)


if __name__ == "__main__":
    main()
